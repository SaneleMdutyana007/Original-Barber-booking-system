create extension if not exists "pgcrypto";

-- ---------- ENUMS ----------
create type public.app_role as enum ('admin', 'client');
create type public.booking_status as enum ('pending', 'confirmed', 'cancelled', 'reschedule_requested');
create type public.payment_status as enum ('unpaid', 'paid', 'refunded');
create type public.request_type as enum ('reschedule', 'cancel');
create type public.request_status as enum ('pending', 'approved', 'rejected');

-- ---------- USER ROLES ----------
create table public.user_roles (
  id          bigint generated by default as identity primary key,
  user_id     uuid references auth.users(id) on delete cascade not null,
  role        public.app_role not null,
  created_at  timestamptz not null default now(),
  unique (user_id, role)
);

-- ---------- PROFILES ----------
create table public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  full_name   text not null,
  phone       text,
  avatar_url  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------- SERVICES ----------
create table public.services (
  id               uuid primary key default gen_random_uuid(),
  name             text not null,
  slug             text not null unique,
  description      text not null default '',
  duration_minutes int not null check (duration_minutes > 0),
  price_zar        numeric(10,2) not null check (price_zar > 0),
  image_path       text,
  image_alt        text not null default '',
  is_active        boolean not null default true,
  sort_order       int not null default 0,
  created_at       timestamptz not null default now()
);

-- ---------- BARBERS ----------
create table public.barbers (
  id            uuid primary key default gen_random_uuid(),
  profile_id    uuid references public.profiles(id) on delete set null,
  display_name  text not null,
  bio           text not null default '',
  specialties   text[] not null default '{}',
  photo_path    text,
  photo_alt     text not null default '',
  is_active     boolean not null default true,
  created_at    timestamptz not null default now()
);

-- ---------- AVAILABILITY ----------
create table public.availability_slots (
  id           uuid primary key default gen_random_uuid(),
  barber_id    uuid not null references public.barbers(id) on delete cascade,
  day_of_week  int not null check (day_of_week between 0 and 6),
  start_time   time not null,
  end_time     time not null,
  check (start_time < end_time)
);

-- ---------- BOOKINGS ----------
create table public.bookings (
  id                   uuid primary key default gen_random_uuid(),
  client_id            uuid not null references public.profiles(id) on delete restrict,
  barber_id            uuid not null references public.barbers(id) on delete restrict,
  service_id           uuid not null references public.services(id) on delete restrict,
  slot_start           timestamptz not null,
  slot_end             timestamptz not null,
  status               public.booking_status not null default 'pending',
  payment_status       public.payment_status not null default 'unpaid',
  payfast_m_payment_id text,
  amount_zar           numeric(10,2) not null check (amount_zar > 0),
  notes                text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  check (slot_end > slot_start)
);

-- Prevent double-booking: only one active booking per barber+slot.
create unique index unique_barber_slot
  on public.bookings (barber_id, slot_start)
  where status in ('pending', 'confirmed');

create index idx_bookings_client on public.bookings (client_id);
create index idx_bookings_barber_slot on public.bookings (barber_id, slot_start);
create index idx_bookings_status on public.bookings (status);

-- ---------- BOOKING REQUESTS ----------
create table public.booking_requests (
  id                    uuid primary key default gen_random_uuid(),
  booking_id            uuid not null references public.bookings(id) on delete cascade,
  requested_by          uuid not null references public.profiles(id) on delete cascade,
  request_type          public.request_type not null,
  requested_slot_start  timestamptz,
  reason                text,
  status                public.request_status not null default 'pending',
  created_at            timestamptz not null default now(),
  resolved_at           timestamptz,
  resolved_by           uuid references public.profiles(id) on delete set null
);

create index idx_requests_booking on public.booking_requests (booking_id);
create index idx_requests_status on public.booking_requests (status);

-- ---------- REVIEWS ----------
create table public.reviews (
  id            uuid primary key default gen_random_uuid(),
  booking_id    uuid not null unique references public.bookings(id) on delete cascade,
  client_id     uuid not null references public.profiles(id) on delete cascade,
  rating        int not null check (rating between 1 and 5),
  comment       text,
  is_published  boolean not null default false,
  created_at    timestamptz not null default now()
);

-- ---------- CASE STUDIES ----------
create table public.case_studies (
  id          uuid primary key default gen_random_uuid(),
  title       text not null,
  slug        text not null unique,
  client_name text not null,
  service_id  uuid references public.services(id) on delete set null,
  summary     text not null default '',
  body_html   text not null default '',
  image_path  text,
  image_alt   text not null default '',
  published   boolean not null default false,
  sort_order  int not null default 0,
  created_at  timestamptz not null default now()
);

-- ---------- FAQS ----------
create table public.faqs (
  id          uuid primary key default gen_random_uuid(),
  question    text not null,
  answer      text not null,
  category    text not null default 'General',
  sort_order  int not null default 0
);

-- ---------- PAGE META (SEO) ----------
create table public.page_meta (
  id          bigint generated by default as identity primary key,
  path        text not null unique,
  title       text not null,
  description text not null
);

-- ---------- AUDIT LOG ----------
create table public.audit_log (
  id          bigint generated by default as identity primary key,
  actor_id    uuid references auth.users(id) on delete set null,
  action      text not null,
  entity      text not null,
  entity_id   text,
  metadata    jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);

-- ---------- updated_at trigger ----------
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

create trigger trg_bookings_touch before update on public.bookings
  for each row execute function public.touch_updated_at();

create trigger trg_profiles_touch before update on public.profiles
  for each row execute function public.touch_updated_at();

-- ---------- Auto-create profile + role on signup ----------
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', 'Client'),
    new.raw_user_meta_data->>'phone'
  );
  insert into public.user_roles (user_id, role) values (new.id, 'client')
  on conflict do nothing;
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();